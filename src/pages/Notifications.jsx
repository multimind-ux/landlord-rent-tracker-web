import { useCallback, useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import {
  AlertTriangle,
  Bell,
  CalendarClock,
  CheckCheck,
  Check,
  Clock3,
  RefreshCw,
} from "lucide-react";
import { api, errorMessage } from "../api";
import ErrorBanner from "../components/ErrorBanner";
import Badge from "../components/ui/Badge";
import Button, { buttonClasses } from "../components/ui/Button";
import Card from "../components/ui/Card";
import EmptyState from "../components/ui/EmptyState";
import FilterChips from "../components/ui/FilterChips";
import PageHeader from "../components/ui/PageHeader";
import { Skeleton } from "../components/ui/Skeleton";
import { useNotifications } from "../context/NotificationContext";
import { useToast } from "../context/ToastContext";
import { cn } from "../utils/cn";
import {
  formatDateTime,
  formatNotificationMessage,
  formatRelativeTime,
} from "../utils/format";

const TYPE_META = {
  due_soon: {
    label: "Due soon",
    tone: "amber",
    icon: Clock3,
    accent: "border-l-amber-400 bg-amber-50/40 dark:bg-amber-500/5",
    iconClass: "bg-amber-100 text-amber-600 dark:bg-amber-500/15 dark:text-amber-400",
  },
  due_today: {
    label: "Due today",
    tone: "indigo",
    icon: CalendarClock,
    accent: "border-l-accent bg-accent-soft/40 dark:bg-accent/5",
    iconClass: "bg-accent-soft text-accent",
  },
  overdue: {
    label: "Overdue",
    tone: "red",
    icon: AlertTriangle,
    accent: "border-l-red-400 bg-red-50/40 dark:bg-red-500/5",
    iconClass: "bg-red-100 text-red-600 dark:bg-red-500/15 dark:text-red-400",
  },
};

function NotificationSkeleton() {
  return (
    <div className="space-y-3" aria-label="Loading notifications">
      {[1, 2, 3, 4].map((item) => (
        <div
          key={item}
          className="rounded-2xl border border-line bg-surface p-5 shadow-card"
        >
          <div className="flex gap-4">
            <Skeleton className="h-10 w-10 rounded-xl" />
            <div className="flex-1 space-y-2">
              <Skeleton className="h-4 w-32" />
              <Skeleton className="h-4 w-full max-w-xl" />
              <Skeleton className="h-3 w-24" />
            </div>
          </div>
        </div>
      ))}
    </div>
  );
}

export default function Notifications() {
  const { toast } = useToast();
  const { markRead, markAllRead, refreshUnreadCount } = useNotifications();
  const [notifications, setNotifications] = useState([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState("");
  const [filter, setFilter] = useState("all");
  const [markingId, setMarkingId] = useState(null);
  const [markingAll, setMarkingAll] = useState(false);

  const load = useCallback(async () => {
    setError("");
    try {
      const { data } = await api.get("/notifications", {
        params: { limit: 100 },
      });
      setNotifications(data);
    } catch (err) {
      setError(errorMessage(err, "Could not load notifications."));
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const unread = useMemo(
    () => notifications.filter((notification) => !notification.is_read),
    [notifications]
  );
  const filtered = filter === "unread" ? unread : notifications;

  async function handleRefresh() {
    setRefreshing(true);
    await load();
    await refreshUnreadCount();
    setRefreshing(false);
  }

  async function handleMarkRead(notification) {
    if (notification.is_read || markingId) return;
    setMarkingId(notification.id);
    try {
      await markRead(notification.id);
      setNotifications((current) =>
        current.map((item) =>
          item.id === notification.id ? { ...item, is_read: true } : item
        )
      );
      toast("Notification marked as read.", "success");
    } catch {
      toast("Could not mark the notification as read.", "error");
    } finally {
      setMarkingId(null);
    }
  }

  async function handleMarkAll() {
    if (unread.length === 0) return;
    setMarkingAll(true);
    try {
      await markAllRead();
      setNotifications((current) =>
        current.map((item) => ({ ...item, is_read: true }))
      );
      toast("All notifications marked as read.", "success");
    } catch {
      toast("Could not mark all notifications as read.", "error");
    } finally {
      setMarkingAll(false);
    }
  }

  return (
    <div className="space-y-6">
      <PageHeader
        title="Notifications"
        description="Rent reminders and overdue alerts generated by the daily reminder job."
        actions={
          <>
            <Button
              variant="secondary"
              icon={RefreshCw}
              onClick={handleRefresh}
              loading={refreshing}
            >
              Refresh
            </Button>
            <Button
              icon={CheckCheck}
              onClick={handleMarkAll}
              loading={markingAll}
              disabled={unread.length === 0}
            >
              Mark all as read
            </Button>
          </>
        }
      />

      <ErrorBanner message={error} onRetry={load} />

      <Card>
        <div className="flex flex-col gap-3 border-b border-line p-4 sm:flex-row sm:items-center sm:justify-between sm:px-5">
          <FilterChips
            value={filter}
            onChange={setFilter}
            options={[
              { value: "all", label: "All", count: notifications.length },
              { value: "unread", label: "Unread", count: unread.length },
            ]}
          />
          <p className="text-xs text-muted">
            Reminders are created automatically each morning.
          </p>
        </div>

        {loading ? (
          <div className="p-4 sm:p-5">
            <NotificationSkeleton />
          </div>
        ) : filtered.length === 0 ? (
          <EmptyState
            icon={Bell}
            title={
              notifications.length === 0
                ? "No notifications yet"
                : "You're all caught up"
            }
            description={
              notifications.length === 0
                ? "Due-soon and overdue reminders will appear here once the daily job runs."
                : "There are no unread notifications right now."
            }
            action={
              notifications.length === 0 ? (
                <Link
                  to="/"
                  className={buttonClasses({ variant: "secondary", size: "sm" })}
                >
                  Back to dashboard
                </Link>
              ) : (
                <Button variant="secondary" onClick={() => setFilter("all")}>
                  View all notifications
                </Button>
              )
            }
          />
        ) : (
          <ul className="divide-y divide-line">
            {filtered.map((notification) => {
              const meta = TYPE_META[notification.type] || TYPE_META.due_soon;
              const Icon = meta.icon;
              return (
                <li
                  key={notification.id}
                  className={cn(
                    "border-l-4 px-4 py-4 sm:px-5",
                    meta.accent,
                    notification.is_read && "opacity-80"
                  )}
                >
                  <div className="flex flex-col gap-3 sm:flex-row sm:items-start">
                    <span
                      className={cn(
                        "flex h-10 w-10 shrink-0 items-center justify-center rounded-xl",
                        meta.iconClass
                      )}
                    >
                      <Icon className="h-4 w-4" aria-hidden="true" />
                    </span>
                    <div className="min-w-0 flex-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <Badge tone={meta.tone}>{meta.label}</Badge>
                        {!notification.is_read && (
                          <Badge tone="indigo" dot>
                            Unread
                          </Badge>
                        )}
                        <span
                          className="text-xs text-muted"
                          title={formatDateTime(notification.created_at)}
                        >
                          {formatRelativeTime(notification.created_at)}
                        </span>
                      </div>
                      <p className="mt-2 text-sm leading-6 text-ink">
                        {formatNotificationMessage(notification.message)}
                      </p>
                      <p className="mt-1 text-[11px] text-muted">
                        {formatDateTime(notification.created_at)}
                      </p>
                    </div>
                    {!notification.is_read && (
                      <Button
                        variant="secondary"
                        size="sm"
                        icon={Check}
                        onClick={() => handleMarkRead(notification)}
                        loading={markingId === notification.id}
                        className="self-start"
                      >
                        Mark as read
                      </Button>
                    )}
                  </div>
                </li>
              );
            })}
          </ul>
        )}
      </Card>
    </div>
  );
}
